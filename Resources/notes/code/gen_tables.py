#!/usr/bin/env python3
# Sinh tables.h (chay trong VM): AES S-box, CRC32, MD5 K, SHA-256/512 K va H0
import math, sys

def rotl8(x, s):
    return ((x << s) | (x >> (8 - s))) & 0xFF

def aes_sbox():
    S = [0] * 256
    p = q = 1
    while True:
        p = (p ^ ((p << 1) & 0xFF) ^ (0x1B if p & 0x80 else 0)) & 0xFF
        q ^= (q << 1) & 0xFF
        q ^= (q << 2) & 0xFF
        q ^= (q << 4) & 0xFF
        if q & 0x80:
            q ^= 0x09
        q &= 0xFF
        x = q ^ rotl8(q, 1) ^ rotl8(q, 2) ^ rotl8(q, 3) ^ rotl8(q, 4)
        S[p] = (x ^ 0x63) & 0xFF
        if p == 1:
            break
    S[0] = 0x63
    return S

def primes(n):
    out, c = [], 2
    while len(out) < n:
        if all(c % d for d in range(2, int(c ** 0.5) + 1)):
            out.append(c)
        c += 1
    return out

def iroot(x, k):
    lo, hi = 0, 1 << ((x.bit_length() // k) + 2)
    while lo < hi:
        mid = (lo + hi + 1) // 2
        if mid ** k <= x:
            lo = mid
        else:
            hi = mid - 1
    return lo

def arr(name, vals, ctype, width):
    fmt = "0x%0" + str(width) + "x"
    sfx = "ULL" if ctype == "uint64_t" else ("u" if ctype == "uint32_t" else "")
    lines = []
    for i in range(0, len(vals), 8 if width <= 8 else 4):
        step = 8 if width <= 8 else 4
        lines.append("    " + ", ".join((fmt % v) + sfx for v in vals[i:i + step]))
    return "static const %s %s[%d] = {\n%s\n};\n" % (ctype, name, len(vals), ",\n".join(lines))

S = aes_sbox()
INV = [0] * 256
for i, v in enumerate(S):
    INV[v] = i
assert S[0x01] == 0x7C and S[0x53] == 0xED and INV[0x63] == 0x00

crc = []
for n in range(256):
    c = n
    for _ in range(8):
        c = (c >> 1) ^ 0xEDB88320 if c & 1 else c >> 1
    crc.append(c)

md5k = [int(abs(math.sin(i + 1)) * (1 << 32)) & 0xFFFFFFFF for i in range(64)]
p80 = primes(80)
k256 = [iroot(p << 96, 3) & 0xFFFFFFFF for p in p80[:64]]
h256 = [iroot(p << 64, 2) & 0xFFFFFFFF for p in p80[:8]]
k512 = [iroot(p << 192, 3) & 0xFFFFFFFFFFFFFFFF for p in p80[:80]]
h512 = [iroot(p << 128, 2) & 0xFFFFFFFFFFFFFFFF for p in p80[:8]]
assert md5k[0] == 0xD76AA478 and k256[0] == 0x428A2F98 and k256[63] == 0xC67178F2
assert h256[0] == 0x6A09E667 and k512[0] == 0x428A2F98D728AE22 and h512[0] == 0x6A09E667F3BCC908

with open(sys.argv[1] if len(sys.argv) > 1 else "tables.h", "w") as f:
    f.write("/* generated by gen_tables.py */\n#include <stdint.h>\n")
    f.write(arr("AES_SBOX", S, "uint8_t", 2))
    f.write(arr("AES_INV_SBOX", INV, "uint8_t", 2))
    f.write(arr("CRC32_TAB", crc, "uint32_t", 8))
    f.write(arr("MD5_K", md5k, "uint32_t", 8))
    f.write(arr("SHA256_K", k256, "uint32_t", 8))
    f.write(arr("SHA256_H0", h256, "uint32_t", 8))
    f.write(arr("SHA512_K", k512, "uint64_t", 16))
    f.write(arr("SHA512_H0", h512, "uint64_t", 16))
print("ok")
